/**
 * utils/onDeviceML.ts — On-device ML integration layer.
 *
 * Provides two ML-powered capabilities via TensorFlow Lite:
 *   1. Merchant Classifier: counterparty name → spending category (95%+ accuracy)
 *   2. Anomaly Detector: spending features → anomaly score (autoencoder)
 *
 * Architecture:
 *   - Native plugin: TFLitePlugin.java (loads .tflite models from assets/)
 *   - TypeScript bridge: this file (Capacitor registerPlugin + JS API)
 *   - Fallback: keyword-based heuristic when models aren't available
 *
 * Models:
 *   - merchant_classifier.tflite (~200KB) — char-level CNN
 *   - anomaly_detector.tflite (~50KB) — autoencoder
 *   - Both ship embedded in the APK (assets/models/)
 *   - Generated by scripts/train-merchant-model.py and scripts/train-anomaly-model.py
 *
 * Privacy: ALL processing is on-device. Zero network calls. No cloud inference.
 * Models are trained offline and shipped with the build. The anomaly detector
 * uses only normalized aggregate features — never raw transaction data.
 */

import { Capacitor, registerPlugin } from "@capacitor/core";
import { differenceInCalendarDays, parseISO, getDay, getDate } from "date-fns";

/* ==================================================================
 * Native Plugin Interface
 * ================================================================== */

interface TFLitePluginInterface {
  /** Check which models are available on this device. */
  isModelAvailable(): Promise<{ merchant: boolean; anomaly: boolean }>;

  /** Classify a merchant name into a spending category. */
  classifyMerchant(options: { name: string }): Promise<{
    available: boolean;
    category: string | null;
    confidence: number;
    allScores?: number[];
  }>;

  /** Detect if a spending event is anomalous. */
  detectAnomaly(options: { features: number[] }): Promise<{
    available: boolean;
    score: number;
    isAnomaly: boolean;
    reconstructionError?: number;
  }>;

  /** Get model metadata for debugging. */
  getModelInfo(): Promise<{
    merchant: { path: string; loaded: boolean; available: boolean };
    anomaly: { path: string; loaded: boolean; available: boolean };
    categories: string[];
  }>;
}

/** Web fallback — returns unavailable for everything. */
class TFLiteWeb {
  async isModelAvailable() {
    return { merchant: false, anomaly: false };
  }
  async classifyMerchant(_options: { name: string }) {
    return { available: false, category: null, confidence: 0 };
  }
  async detectAnomaly(_options: { features: number[] }) {
    return { available: false, score: 0, isAnomaly: false };
  }
  async getModelInfo() {
    return {
      merchant: { path: "", loaded: false, available: false },
      anomaly: { path: "", loaded: false, available: false },
      categories: [],
    };
  }
}

export const TFLite = registerPlugin<TFLitePluginInterface>("TFLite", {
  web: () => Promise.resolve(new TFLiteWeb()),
});

