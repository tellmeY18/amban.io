function keywordClassify(name: string): { category: SpendCategory; confidence: number } {
  const lower = name.toLowerCase();
  for (const [category, keywords] of Object.entries(CATEGORY_KEYWORDS)) {
    for (const keyword of keywords) {
      if (lower.includes(keyword)) {
        return { category: category as SpendCategory, confidence: 0.75 };
      }
    }
  }
  return { category: "other", confidence: 0.3 };
}

/* ==================================================================
 * Public API: Merchant Classification
 *
 * Tries TFLite model first; falls back to keyword heuristic.
 * The caller gets a category + confidence regardless of which path ran.
 * ================================================================== */

/** Result of merchant categorization. */
export interface ClassificationResult {
  category: SpendCategory;
  confidence: number;
  source: "tflite" | "heuristic";
}

/**
 * Classify a merchant/counterparty name into a spending category.
 *
 * Uses the TFLite char-level CNN model when available (Android with
 * model file present). Falls back to keyword matching on web or when
 * the model isn't shipped yet.
 *
 * @param counterparty  The merchant or counterparty name from SMS.
 * @returns             Category, confidence (0-1), and which engine was used.
 */
export async function categorizeMerchant(
  counterparty: string | null,
): Promise<ClassificationResult> {
  if (!counterparty || counterparty.trim().length === 0) {
    return { category: "other", confidence: 0, source: "heuristic" };
  }

  const name = counterparty.trim();

  // Try TFLite model first (Android only)
  if (Capacitor.getPlatform() === "android") {
    try {
      const result = await TFLite.classifyMerchant({ name });
      if (result.available && result.category && result.confidence > 0.5) {
        return {
          category: result.category as SpendCategory,
          confidence: result.confidence,
          source: "tflite",
        };
      }
    } catch {
      // Model unavailable or inference failed — fall through to heuristic
    }
  }

  // Fallback: keyword-based classification
  const heuristic = keywordClassify(name);
  return { ...heuristic, source: "heuristic" };
}

/**
 * Synchronous keyword-only classification.
 * Use this when you can't await (e.g., in a pure generator function).
 */
export function categorizeMerchantSync(counterparty: string | null): SpendCategory {
  if (!counterparty) return "other";
  return keywordClassify(counterparty).category;
}

/* ==================================================================
 * Public API: Anomaly Detection
 *
 * Takes a spending event's features and returns an anomaly score.
 * Uses the TFLite autoencoder when available; falls back to z-score.
 * ================================================================== */

/** Features extracted from a spending event for anomaly detection. */
export interface SpendingFeatures {
  /** Raw spend amount. */
  amount: number;
  /** Day of week (0=Sun, 6=Sat). */
  dayOfWeek: number;
  /** Day of month (1-31). */
  dayOfMonth: number;
  /** User's historical average daily spend. */
  avgDailySpend: number;
  /** User's standard deviation of daily spend. */
  stdDevSpend: number;
}

/** Result of anomaly detection. */
export interface AnomalyResult {
  /** Anomaly score between 0 (normal) and 1 (highly anomalous). */
  score: number;
  /** Whether this crosses the anomaly threshold. */
  isAnomaly: boolean;
  /** Which detection method was used. */
  source: "tflite" | "statistical";
}

/**
 * Normalize raw features into the [0,1] range expected by the model.
 */
function normalizeFeatures(features: SpendingFeatures): number[] {
  const amountNorm =
    features.avgDailySpend > 0
      ? Math.min(features.amount / (features.avgDailySpend * 5), 1.0)
      : 0.5;
  const dowNorm = features.dayOfWeek / 6.0;
  const domNorm = (features.dayOfMonth - 1) / 30.0;
  const isWeekend = features.dayOfWeek === 0 || features.dayOfWeek === 6 ? 1.0 : 0.0;
  const ratioToAvg =
    features.avgDailySpend > 0
      ? Math.min(features.amount / features.avgDailySpend, 5.0) / 5.0
      : 0.5;

  return [amountNorm, dowNorm, domNorm, isWeekend, ratioToAvg];
}

/**
 * Statistical fallback for anomaly detection using z-score.
 */
function statisticalAnomalyScore(features: SpendingFeatures): number {
  if (features.stdDevSpend <= 0 || features.avgDailySpend <= 0) return 0;
  const z = Math.abs(features.amount - features.avgDailySpend) / features.stdDevSpend;
  // Map z-score to 0-1 using sigmoid
  return 1.0 / (1.0 + Math.exp(-1.5 * (z - 2.0)));
}

/**
 * Detect whether a spending event is anomalous.
 *
 * Uses the TFLite autoencoder model when available. The model is trained
 * on "normal" spending patterns; high reconstruction error = anomaly.
 * Falls back to z-score analysis on web or when model isn't available.
 *
 * @param features  Normalized spending event features.
 * @returns         Anomaly score (0-1), isAnomaly flag, and source.
 */
export async function detectAnomaly(features: SpendingFeatures): Promise<AnomalyResult> {
  const normalized = normalizeFeatures(features);

  // Try TFLite model first
  if (Capacitor.getPlatform() === "android") {
    try {
      const result = await TFLite.detectAnomaly({ features: normalized });
      if (result.available) {
        return {
          score: result.score,
          isAnomaly: result.isAnomaly,
          source: "tflite",
        };
      }
    } catch {
      // Fall through to statistical
    }
  }

  // Statistical fallback
  const score = statisticalAnomalyScore(features);
  return {
    score,
    isAnomaly: score > 0.5,
    source: "statistical",
  };
}

/* ==================================================================
 * Spending Pattern Analysis
 * ================================================================== */

export interface SpendingPattern {
  dayOfWeekAvg: number[];
  dayOfMonthAvg: number[];
  trendSlope: number;
  volatility: number;
  topMerchants: Array<{ name: string; total: number; count: number; category: SpendCategory }>;
}

/**
 * Analyze spending patterns from logs and SMS transactions.
 */
export async function analyzeSpendingPatterns(
  logs: ReadonlyArray<{ logDate: string; spent: number }>,
  transactions?: ReadonlyArray<{
    amount: number;
    counterparty: string | null;
    receivedAt: string;
  }>,
): Promise<SpendingPattern> {
  // Day of week analysis
  const dayOfWeekSums: number[] = Array(7).fill(0);
  const dayOfWeekCounts: number[] = Array(7).fill(0);

  for (const log of logs) {
    const date = parseISO(log.logDate);
    const dow = getDay(date);
    dayOfWeekSums[dow] = (dayOfWeekSums[dow] ?? 0) + log.spent;
    dayOfWeekCounts[dow] = (dayOfWeekCounts[dow] ?? 0) + 1;
  }

  const dayOfWeekAvg = dayOfWeekSums.map((sum, i) =>
    (dayOfWeekCounts[i] ?? 0) > 0 ? (sum ?? 0) / (dayOfWeekCounts[i] ?? 1) : 0,
  );

  // Day of month analysis
  const dayOfMonthSums: number[] = Array(31).fill(0);
  const dayOfMonthCounts: number[] = Array(31).fill(0);

  for (const log of logs) {
    const day = getDate(parseISO(log.logDate)) - 1;
    dayOfMonthSums[day] = (dayOfMonthSums[day] ?? 0) + log.spent;
    dayOfMonthCounts[day] = (dayOfMonthCounts[day] ?? 0) + 1;
  }

  const dayOfMonthAvg = dayOfMonthSums.map((sum, i) =>
    (dayOfMonthCounts[i] ?? 0) > 0 ? (sum ?? 0) / (dayOfMonthCounts[i] ?? 1) : 0,
  );

  // Trend analysis
  const today = new Date();
  const points = logs.map((log) => ({
    x: differenceInCalendarDays(today, parseISO(log.logDate)),
    y: log.spent,
  }));

  let trendSlope = 0;
  if (points.length >= 5) {
    const n = points.length;
    let sumX = 0,
      sumY = 0,
      sumXY = 0,
      sumX2 = 0;
    for (const p of points) {
      sumX += p.x;
      sumY += p.y;
      sumXY += p.x * p.y;
      sumX2 += p.x * p.x;
    }
    const denom = n * sumX2 - sumX * sumX;
    if (denom !== 0) {
      trendSlope = -(n * sumXY - sumX * sumY) / denom;
    }
  }

  // Volatility
  const spends = logs.map((l) => l.spent).filter((s) => s > 0);
  const avg = spends.length > 0 ? spends.reduce((a, b) => a + b, 0) / spends.length : 0;
  let volatility = 0;
  if (spends.length > 1 && avg > 0) {
    const variance = spends.reduce((sum, s) => sum + (s - avg) ** 2, 0) / (spends.length - 1);
    volatility = Math.sqrt(variance) / avg;
  }

  // Merchant analysis with ML classification
  const merchantMap = new Map<string, { total: number; count: number }>();
  if (transactions) {
    for (const txn of transactions) {
      if (!txn.counterparty) continue;
      const name = txn.counterparty.toLowerCase().trim();
      const existing = merchantMap.get(name) ?? { total: 0, count: 0 };
      existing.total += txn.amount;
      existing.count += 1;
      merchantMap.set(name, existing);
    }
  }

  // Classify top merchants (use sync heuristic for bulk; TFLite for top 5)
  const sortedMerchants = Array.from(merchantMap.entries())
    .sort((a, b) => b[1].total - a[1].total)
    .slice(0, 10);

  const topMerchants: SpendingPattern["topMerchants"] = [];
  for (const [name, data] of sortedMerchants) {
    const classification = await categorizeMerchant(name);
    topMerchants.push({
      name,
      total: data.total,
      count: data.count,
      category: classification.category,
    });
  }

  return {
    dayOfWeekAvg,
    dayOfMonthAvg,
    trendSlope,
    volatility,
    topMerchants,
  };
}

/* ==================================================================
 * Model Management
 * ================================================================== */

/** Check if ML models are available on this device. */
export async function checkMLAvailability(): Promise<{
  merchantClassifier: boolean;
  anomalyDetector: boolean;
  platform: string;
}> {
  const platform = Capacitor.getPlatform();
  if (platform !== "android") {
    return { merchantClassifier: false, anomalyDetector: false, platform };
  }

  try {
    const result = await TFLite.isModelAvailable();
    return {
      merchantClassifier: result.merchant,
      anomalyDetector: result.anomaly,
      platform,
    };
  } catch {
    return { merchantClassifier: false, anomalyDetector: false, platform };
  }
}
